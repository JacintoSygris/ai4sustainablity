export function ui(locale, message) {
  if (locale === "es" && message === "ESRS 2") return "NEIS 2"
  return locale === "en" ? english[message] ?? learningEnglish[message] ?? studyEnglish[message] ?? wave2English[message] ?? message : message
}

// Only use for system presentation objects, never drafts, facts or evidence.
export function translateSystem(value, locale = "es") {
  if (typeof value === "string") return ui(locale, value)
  if (Array.isArray(value)) return value.map(item => translateSystem(item, locale))
  if (value && typeof value === "object") return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, translateSystem(item, locale)]))
  return value
}

// Parameters are inserted after selecting static copy and are never translated.
export function formatUi(locale, message, values) {
  return ui(locale, message).replace(/\{(\d+)\}/g, (_, index) => String(values[Number(index)] ?? ""))
}
export function hasEnglishCopy(message) { return Object.hasOwn(english, message) || Object.hasOwn(learningEnglish, message) || Object.hasOwn(studyEnglish, message) || Object.hasOwn(wave2English, message) }
